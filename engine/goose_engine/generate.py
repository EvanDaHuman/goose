def import_block(text_names, kept_imports, pkg, local_defs, from_services=None):
    lines = []
    fastapi_names = sorted(n for n in ("APIRouter", "Depends", "Request") if n in text_names)
    if fastapi_names:
        lines.append(f"from fastapi import {', '.join(fastapi_names)}")
    std = []
    for imp in kept_imports:
        try:
            st = ast.parse(imp).body[0]
        except SyntaxError:
            continue
        if P.defined_names(st) & text_names:
            std.append(imp)
    grouped = defaultdict(set)
    for name, line in HELPERS.items():
        if name in text_names:
            stmt = line.format(pkg=pkg)
            if stmt.startswith("from decimal") or stmt.startswith("from typing"):
                std.append(stmt)
            else:
                mod, nm = stmt.split(" import ")
                grouped[mod].add(nm)
    if "Db" in text_names or "get_db" in text_names:
        grouped[f"from {pkg}db"].update(n for n in ("Db", "get_db") if n in text_names)
    if from_services:
        used = sorted(n for n in from_services if n in text_names)
        if used:
            grouped[f"from {pkg}services"].update(used)
    out = sorted(set(std), key=lambda s: (not s.startswith("import"), s)) + lines
    local = [f"{mod} import {', '.join(sorted(names))}" for mod, names in sorted(grouped.items())]
    return "\n".join(out) + ("\n\n" if out else "") + "\n".join(local) + ("\n" if local else "")


def generate(repo, assessment, scope, out):
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    (out / "app" / "routes").mkdir(parents=True)
    (out / "migrations").mkdir()
    (out / "migrate").mkdir()
    (out / "tests").mkdir()
    changes, warnings = Changes(), []
    modules, problems = ci.scan(repo)
    app_modules = [m for m in modules if not ci.is_test_file(m.rel)]
    groups, services, imports = defaultdict(list), [], []
    structure = app_structure(app_modules)
    for mod in app_modules:
        ModulePort(mod, assessment, scope, changes, warnings, structure).run(groups, services, imports)

    # services.py: everything that is not a route, minus what became unused
    route_names = set()
    for items in groups.values():
        for it in items:
            route_names |= P.names_in(it["text"])
    while True:
        all_names = set(route_names)
        for s in services:
            all_names |= P.names_in(s["text"]) - s["defines"]
        drop = [s for s in services if s["defines"] and not (s["defines"] & all_names)]
        if not drop:
            break
        for s in drop:
            changes.add(", ".join(sorted(s["defines"])), "removed", "no longer used after the port")
            services.remove(s)
    svc_text = "\n".join(s["text"].rstrip() + "\n" for s in sorted(services, key=lambda s: s["line"]))
    svc_names = P.names_in(svc_text)
    svc_defs = set().union(*[s["defines"] for s in services]) if services else set()
    header = ('"""Business rules and shared helpers, ported from the original application.\n\n'
              'Moved here unchanged except for the edits Goose lists in CHANGES.md.\n"""\n')
    (out / "app" / "services.py").write_text(
        header + import_block(svc_names, imports, ".", svc_defs) + "\n\n" + svc_text)

    group_files = []
    for g, items in sorted(groups.items()):
        body = "\n\n".join(it["text"].strip("\n") + "\n" for it in sorted(items, key=lambda x: x["order"]))
        names = P.names_in(body) | set().union(*[it["uses"] for it in items])
        names |= {"APIRouter"}
        text = (f'"""Routes under /{g} (ported from the Flask application)."""\n'
                + import_block(names, imports, "..", set(), svc_defs)
                + f'\nrouter = APIRouter(tags=["{g}"])\n\n\n' + body)
        (out / "app" / "routes" / f"{g}.py").write_text(text)
        group_files.append(g)
    (out / "app" / "routes" / "__init__.py").write_text("")
    (out / "app" / "__init__.py").write_text("")

    # fixed modules
    for name in ("db.py", "compat.py", "idempotency.py"):
        shutil.copy(TEMPLATES / "app" / name, out / "app" / name)
    settings = (TEMPLATES / "app" / "settings.py").read_text()
    settings = settings.replace("__APP_SLUG__", scope["app_slug"]).replace("__TIMEZONE__", scope["timezone"]) \
        .replace("__DATETIME_FORMAT__", scope["datetime_output_format"])
    (out / "app" / "settings.py").write_text(settings)
    title = scope.get("app_title") or scope["app_slug"]
    imports_routes = ", ".join(group_files)
