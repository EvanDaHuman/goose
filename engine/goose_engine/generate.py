class Changes:
    def __init__(self):
        self.items = []

    def add(self, where, what, detail=""):
        item = {"where": where, "what": what, "detail": detail}
        if item not in self.items:
            self.items.append(item)


def pg_type(table, col, scope, tables, fk_cols):
    full = f"{table}.{col['name']}"
    t = col["decl_type"]
    if col["pk"] and "INT" in t:
        return "BIGINT GENERATED BY DEFAULT AS IDENTITY"
    if full in scope["money_columns"]:
        return "NUMERIC(12,2)"
    if full in scope["timestamp_columns"]:
        return "TIMESTAMPTZ"
    if full in scope["date_columns"]:
        return "DATE"
    if "INT" in t or t in ("BOOLEAN", "BOOL"):
        return "BIGINT"
    if t in ("REAL", "FLOAT", "DOUBLE", "DOUBLE PRECISION"):
        return "DOUBLE PRECISION"
    m = re.match(r"(NUMERIC|DECIMAL)\s*(\(.*\))?", t)
    if m:
        return "NUMERIC" + (m.group(2) or "")
    if "BLOB" in t:
        return "BYTEA"
    return "TEXT"


def ddl_default(value, pgt):
    if value is None:
        return ""
    v = str(value).strip()
    if v.upper() in ("CURRENT_TIMESTAMP", "CURRENT_DATE", "CURRENT_TIME"):
        return f" DEFAULT {v.upper()}"
    if re.fullmatch(r"-?\d+(\.\d+)?", v) or re.fullmatch(r"'[^']*'", v):
        return f" DEFAULT {v}"
    return ""


def build_schema_sql(assessment, scope):
    tables = assessment["tables"]
    order = sqltools.table_order(list(tables), {t: tables[t]["foreign_keys"] for t in tables})
    unlinked = {(o["table"], o["column"]) for o in scope["orphan_decisions"] if o["decision"] == "keep_unlinked"}
    roles = scope["roles"]
    out = ["-- PostgreSQL schema generated by Goose from the SQLite schema of the original application.",
           "-- Column types: money columns are NUMERIC(12,2); shop-time text timestamps are TIMESTAMPTZ.", ""]
    notes = []
    for t in order:
        info = tables[t]
        fk_cols = {fk["column"]: fk for fk in info["foreign_keys"]}
        lines = []
        pk_cols = [c["name"] for c in sorted(info["columns"], key=lambda c: c["pk"]) if c["pk"]]
        for c in info["columns"]:
            pgt = pg_type(t, c, scope, tables, fk_cols)
            line = f'    "{c["name"]}" {pgt}'
            if c["pk"] and len(pk_cols) == 1:
                line += " PRIMARY KEY"
            if c["notnull"] and not c["pk"]:
                line += " NOT NULL"
            line += ddl_default(c["default"], pgt)
            unique = any(ix["unique"] and ix["origin"] == "u" and ix["columns"] == [c["name"]] for ix in info["indexes"])
            if unique:
                line += " UNIQUE"
            if c["name"] in fk_cols and (t, c["name"]) not in unlinked:
                fk = fk_cols[c["name"]]
                line += f' REFERENCES "{fk["ref_table"]}" ("{fk["ref_column"]}")'
            elif (t, c["name"]) in unlinked:
                notes.append(f"{t}.{c['name']}: link to {fk_cols[c['name']]['ref_table']} not enforced (agreed).")
            if t == roles.get("product") and c["name"] == roles.get("stock_column") and any(
                    ch["id"] == "stock_never_negative" for ch in scope["changes"]):
                line += f' CHECK ("{c["name"]}" >= 0)'
            lines.append(line)
        if len(pk_cols) > 1:
            lines.append("    PRIMARY KEY (" + ", ".join(f'"{p}"' for p in pk_cols) + ")")
        out.append(f'CREATE TABLE "{t}" (\n' + ",\n".join(lines) + "\n);\n")
    for t in order:
        for ix in tables[t]["indexes"]:
            if ix["origin"] == "c":
                uq = "UNIQUE " if ix["unique"] else ""
                cols = ", ".join(f'"{c}"' for c in ix["columns"])
                out.append(f'CREATE {uq}INDEX "{ix["name"]}" ON "{t}" ({cols});')
    out.append("")
    support = ["-- Support tables added by the upgrade.",
               "CREATE TABLE idempotency_keys (",
               "    key TEXT PRIMARY KEY,",
               "    request_hash TEXT NOT NULL,",
               "    status_code INTEGER NOT NULL,",
               "    body TEXT NOT NULL,",
               "    created_at TIMESTAMPTZ NOT NULL DEFAULT now()",
               ");", ""]
    return "\n".join(out) + "\n", "\n".join(support) + "\n", order, notes


def build_plan(assessment, scope, order):
    tables = assessment["tables"]
    plan_tables = []
    skips = {(o["table"], o["column"]): o["missing_ids"] for o in scope["orphan_decisions"] if o["decision"] == "remove"}
    for t in order:
        info = tables[t]
        cols = []
        for c in info["columns"]:
            full = f"{t}.{c['name']}"
            zone = None
            if full in scope["money_columns"]:
                conv = "money"
            elif full in scope["timestamp_columns"]:
                conv = "local_timestamp"
                zone = (scope.get("timestamp_zones") or {}).get(full)
            elif full in scope["date_columns"]:
                conv = "local_date"
            elif "INT" in c["decl_type"] or c["decl_type"] in ("BOOLEAN", "BOOL"):
                conv = "int"
            elif c["decl_type"] in ("REAL", "FLOAT", "DOUBLE"):
                conv = "float"
            elif "BLOB" in c["decl_type"]:
                conv = "bytes"
            else:
                conv = "text"
            entry = {"name": c["name"], "convert": conv}
            if conv == "local_timestamp" and zone and zone != scope["timezone"]:
                entry["zone"] = zone
            if full in scope["status_mappings"]:
                entry["map"] = scope["status_mappings"][full]
            cols.append(entry)
        pk = [c["name"] for c in info["columns"] if c["pk"]]
        entry = {"name": t, "pk": pk[0] if len(pk) == 1 else None, "columns": cols,
                 "identity": len(pk) == 1 and any(c["pk"] and "INT" in c["decl_type"] for c in info["columns"]),
                 "sequence_floor": info.get("sqlite_sequence") or info.get("max_id")}
        sk = {col: ids for (tt, col), ids in skips.items() if tt == t}
        if sk:
            entry["skip_values"] = sk
        plan_tables.append(entry)
    placeholders = []
    for o in scope["orphan_decisions"]:
        if o["decision"] == "placeholder":
            ref_table = o["references"].split(".")[0]
            for p in o["placeholders"]:
                placeholders.append({"table": ref_table, "values": p})
    return {"generated_by": "Goose", "timezone": scope["timezone"],
            "ambiguous_time_rule": scope["ambiguous_time_rule"],
            "datetime_formats": scope["datetime_input_formats"], "tables": plan_tables,
            "placeholders": placeholders}


def app_structure(app_modules):
    """Across all modules: functions that open SQLite, app factories, and the app's own module names."""
    getters, factories, names = set(), set(), set()
    for m in app_modules:
        parts = list(m.rel.with_suffix("").parts)
        if parts[-1] == "__init__":
            parts = parts[:-1]
        if parts:
            names.add(parts[0])
        for fn in m.functions.values():
            seg = ast.get_source_segment(m.source, fn) or ""
            if "sqlite3.connect" in seg:
                getters.add(fn.name)
            if any(isinstance(n, ast.Call) and ci.dotted(n.func).endswith("Flask") for n in ast.walk(fn)):
                factories.add(fn.name)
    return getters, factories, names


class ModulePort:
    def __init__(self, mod, assessment, scope, changes, warnings, structure=(set(), set(), set())):
        self.mod = mod
        self.global_getters, self.factories, self.app_names = structure
        self.src = P.Source(mod.source)
        self.assessment = assessment
        self.scope = scope
        self.changes = changes
        self.warnings = warnings
        rel = str(mod.rel)
        self.routes = defaultdict(list)
        for r in assessment["routes"]:
            if r["module"] == rel:
                self.routes[r["function"]].append(r)
        self.rule_fns = {r["function"] for r in scope["rules"] if r["module"] == rel}
        self.money_consts = {t[k] for r in scope["rules"] if r["module"] == rel for t in r["tiers"]
                             for k in ("min_name", "rate_name") if t.get(k)}
        self.db_getters, self.dropped = set(), set()
        for fn in mod.functions.values():
            seg = ast.get_source_segment(mod.source, fn) or ""
            if "sqlite3.connect" in seg:
                self.db_getters.add(fn.name)
            if any(ci.dotted(d.func if isinstance(d, ast.Call) else d).split(".")[-1].startswith(("teardown", "after_request"))
                   for d in fn.decorator_list):
                self.dropped.add(fn.name)
            # init_app(app): registers teardown hooks; factories: build the Flask app - FastAPI does both in app/main.py
            if re.search(r"\.(teardown_appcontext|teardown_request|before_request|after_request)\(", seg) or fn.name in self.factories:
                self.dropped.add(fn.name)
        for n in mod.tree.body:   # get_db imported from another module of the app
            if isinstance(n, ast.ImportFrom):
                for a in n.names:
                    if a.name in self.global_getters:
                        self.db_getters.add(a.asname or a.name)
        self.zones = {c.split(".")[1]: z for c, z in (scope.get("timestamp_zones") or {}).items()}
        self.needs_db = set()
        changed = True
        while changed:
            changed = False
            for fn in mod.functions.values():
                if fn.name in self.db_getters or fn.name in self.routes or fn.name in self.needs_db:
                    continue
                called = {n.func.id for n in ast.walk(fn) if isinstance(n, ast.Call) and isinstance(n.func, ast.Name)}
                if called & (self.db_getters | self.needs_db):
                    self.needs_db.add(fn.name)
                    changed = True
        self.sql_edits = self._sql_edits()

    def _sql_edits(self):
        tables = self.assessment["tables"]
        pk_of = {t: next((c["name"] for c in info["columns"] if c["pk"]), None) for t, info in tables.items()}
        int_pk = {t for t, info in tables.items() if any(c["pk"] and "INT" in c["decl_type"] for c in info["columns"])}
        edits = {}
        for fn in self.mod.functions.values():
            if fn.name in self.db_getters or fn.name in self.dropped:
                continue
            for call, text, nodes in ci.execute_calls(fn):
                if text is None:
                    self.warnings.append(f"{self.mod.rel}:{call.lineno} SQL built at run time was not translated")
                    continue
                parsed = sqltools.parse(text)
                for idx, node in enumerate(nodes):
                    ret = None
                    if idx == len(nodes) - 1 and len(nodes) == 1 and parsed["kind"] == "INSERT" \
                            and parsed["table"] in int_pk:
                        ret = pk_of[parsed["table"]]
                    a, b = self.src.span(node)
                    seg = self.src.text[a:b]
                    new, applied = P.translate_string_tokens(seg, ret, self.zones)
                    if new is not None and new != seg:
                        edits[(a, b)] = new
                        for rule in applied:
                            self.changes.add(f"{self.mod.rel}:{node.lineno}", "SQL for PostgreSQL", rule)
        return edits

    def port_function(self, fn, is_route):
        col = P.EditCollector(self.src, fn, is_route=is_route, db_getters=self.db_getters,
                              needs_db_helpers=self.needs_db, sql_edits=self.sql_edits,
                              rule_fn=fn.name in self.rule_fns, changes=self.changes).run()
        start = P.leading_comments_start(self.src, fn)
        end = P.stmt_end(self.src, fn)
        edits = list(col.edits)
        indent = P.body_indent(self.src, fn)
        first_body = fn.body[1] if P.is_docstring(fn.body[0]) and len(fn.body) > 1 else fn.body[0]
        insert_at = self.src.starts[first_body.lineno - 1]
        uses = set(col.uses)
        extra_funcs = []
        if fn.name in self.needs_db:
            a, b = P.def_params_span(self.src, fn)
            has = self.src.text[a:b].strip()
            edits.append((b, b, (", " if has else "") + "db"))
        if is_route:
            recs = self.routes[fn.name]
            kinds = {r["kind"] for r in recs}
            change_ids = {c["id"] for c in self.scope["changes"]}
            roles = self.scope["roles"]
            for d in fn.decorator_list:
                if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute) and d.func.attr in (
                        "route", "get", "post", "put", "patch", "delete"):
                    edits.append((self.src.starts[d.lineno - 1], P.stmt_end(self.src, d), ""))  # remove the whole "@..." line
            decorators = []
            for r in recs:
                path = P.path_for_fastapi(r["flask_path"])
                extra = self._openapi_example(r)
                if len(r["methods"]) == 1:
                    decorators.append(f'@router.{r["methods"][0].lower()}("{path}"{extra})')
                else:
                    decorators.append(f'@router.api_route("{path}", methods={r["methods"]!r}{extra})')
            params = []
            seen = set()
            for r in recs:
                for p in r["path_params"]:
                    if p["name"] not in seen:
                        seen.add(p["name"])
                        params.append(f'{p["name"]}: {"str" if p["type"] == "path" else p["type"]}')
            locked = "transactions_and_locks" in change_ids and kinds & {"place_order", "cancel_order", "restock"}
            if locked:
                uses.add("db")
                edits.append((insert_at, insert_at,
                              f'{indent}db.lock("stock")  # one order at a time: stock checks and updates cannot interleave\n'))
                self.changes.add(fn.name, "stock lock", "stock checks and updates run under a lock")
            if "cancel_order" in kinds and "cancel_once" in change_ids and roles.get("cancelled_value"):
                idx, var = P.find_none_check(fn)
                final = next((st for st in reversed(fn.body) if isinstance(st, ast.Return)), None)
                if idx is not None and final is not None:
                    fa, fb = self.src.span(final)
                    final_text = P.apply_edits(self.src.text[fa:fb], [e for e in edits if fa <= e[0] and e[1] <= fb], fa)
                    after = P.stmt_end(self.src, fn.body[idx])
                    guard = (f'{indent}if {var}["{roles["status_column"]}"] == "{roles["cancelled_value"]}":\n'
                             f'{indent}    # already cancelled: change nothing (agreed fix - cancelling twice used to add stock twice)\n'
                             f'{indent}    {final_text}\n')
                    edits.append((after, after, guard))
                    self.changes.add(fn.name, "cancel once", "a second cancel returns the order unchanged")
                else:
                    self.warnings.append(f"{fn.name}: could not place the cancel-once guard automatically")
            if "request" in uses or "query_get" in uses:
                pass
            params.append("request: Request")
            if col.json_call is not None:
                f, s = col.json_call["force"], col.json_call["silent"]
                params.append(f"payload: Any = Depends(json_body(force={f}, silent={s}))")
                uses.add("json_body")
            if "db" in uses:
                params.append("db: Db = Depends(get_db)")
            a, b = P.def_params_span(self.src, fn)
            idem = "place_order" in kinds and "idempotency_keys" in change_ids
            if idem:
                impl = f"_{fn.name}"
                name_pos = self.src.text.index(fn.name, self.src.off(fn.lineno, fn.col_offset))
                edits.append((name_pos, name_pos + len(fn.name), impl))
                plain = [p.split(":")[0] for p in params]
                edits.append((a, b, ", ".join(plain)))
                call_args = ", ".join(plain)
                wrapper = "\n".join(decorators) + "\n" + (
                    f"def {fn.name}({', '.join(params)}):\n"
                    f'    """{(ast.get_docstring(fn) or recs[0]["methods"][0] + " " + recs[0]["path"]).splitlines()[0]}\n\n'
                    f'    Send an Idempotency-Key header to make retries safe: the same key returns the first\n'
                    f'    response instead of creating a second record.\n    """\n'
                    f'    key = request.headers.get("Idempotency-Key")\n'
                    f"    if key:\n"
                    f"        return idempotency.run(db, key, payload, lambda: {impl}({call_args}))\n"
                    f"    return {impl}({call_args})\n")
                extra_funcs.append(wrapper)
                uses.add("idempotency")
                self.changes.add(fn.name, "idempotency key", "Idempotency-Key header makes retries safe")
            else:
                edits.append((a, b, ", ".join(params)))
                def_line_start = self.src.starts[fn.lineno - 1]
                def_line = self.src.lines[fn.lineno - 1]
                def_indent = def_line[: len(def_line) - len(def_line.lstrip())]
                edits.append((def_line_start, def_line_start, "".join(def_indent + d + "\n" for d in decorators)))
            uses |= {"Request", "Any", "Depends"}
        text = P.apply_edits(self.src.text[start:end], [e for e in edits if start <= e[0] and e[1] <= end], start)
        text = textwrap.dedent(text)
        if extra_funcs:
            text = "\n\n".join(extra_funcs) + "\n\n" + text
        return text, uses

    def _openapi_example(self, r):
        if r["methods"][0] not in ("POST", "PUT", "PATCH") or not r["payload"]["keys"]:
            return ""
        roles = self.scope["roles"]
        ex = {}
        table = (r.get("kind_info") or {}).get("table")
        cols = {c["name"]: c for c in self.assessment["tables"].get(table, {}).get("columns", [])} if table else {}
        for k in r["payload"]["keys"]:
            if k == r["payload"]["list_key"]:
                item = {}
                for ik in r["payload"]["item_keys"]:
                    item[ik] = 1
                ex[k] = [item]
            elif k.endswith("_id") or k in ("quantity", "qty", "stock"):
                ex[k] = 1
            elif k in cols and "INT" in cols[k]["decl_type"]:
                ex[k] = 1
            elif k in cols and cols[k]["decl_type"] in ("REAL", "FLOAT", "DOUBLE", "NUMERIC"):
                ex[k] = 9.99
            else:
                ex[k] = f"example {k}"
        schema = {"requestBody": {"content": {"application/json": {"example": ex}}}}
        return f", openapi_extra={json.dumps(schema)}"

    def run(self, groups, services, imports):
        mod = self.mod
        for st in mod.tree.body:
            if isinstance(st, (ast.Import, ast.ImportFrom)):
                names = {a.name.split(".")[0] for a in st.names} if isinstance(st, ast.Import) else {(st.module or "").split(".")[0]}
                if names & DROP_FLASK:
                    self.changes.add(str(mod.rel), "imports", "Flask and sqlite3 imports replaced")
                    continue
                if isinstance(st, ast.ImportFrom) and (st.level > 0 or names & self.app_names) or \
                        isinstance(st, ast.Import) and names & self.app_names:
                    self.changes.add(str(mod.rel), "imports", f"app-internal import removed: {self.src.seg(st)}")
                    continue
                imports.append(self.src.seg(st))
                continue
            if isinstance(st, ast.FunctionDef):
                if st.name in self.factories:
                    for inner in ast.walk(st):
                        if isinstance(inner, ast.FunctionDef) and inner is not st and inner.name in self.routes:
                            text, uses = self.port_function(inner, True)
                            recs = self.routes[inner.name]
                            g = P.group_name(recs[0]["path"])
                            groups[g].append({"order": (min(r["path"].count("{") for r in recs), inner.lineno), "text": text, "uses": uses})
                            self.changes.add(inner.name, "moved", f"route defined inside {st.name}() is now a normal route")
                    self.changes.add(st.name, "removed", "the Flask app factory; the FastAPI app is created in app/main.py")
                    continue
                if st.name in self.db_getters or st.name in self.dropped:
                    self.changes.add(st.name, "removed", "connection handling moved to app/db.py")
                    continue
                if st.name in self.routes:
                    text, uses = self.port_function(st, True)
                    recs = self.routes[st.name]
                    g = P.group_name(recs[0]["path"])
                    dynamic = min(r["path"].count("{") for r in recs)
                    groups[g].append({"order": (dynamic, st.lineno), "text": text, "uses": uses})
                    continue
                text, uses = self.port_function(st, False)
                services.append({"text": text, "uses": uses, "defines": {st.name}, "line": st.lineno})
                continue
            if isinstance(st, ast.Assign) and isinstance(st.value, ast.Call):
                fname = ci.dotted(st.value.func)
                if fname.split(".")[-1] in self.factories:
                    self.changes.add(str(mod.rel), "removed", f"{self.src.seg(st)} (the FastAPI app is in app/main.py)")
                    continue
                if fname.endswith(("Flask", "Blueprint")):
                    self.changes.add(str(mod.rel), "removed", f"{self.src.seg(st)} (FastAPI app is in app/main.py)")
                    continue
            if isinstance(st, ast.Expr) and isinstance(st.value, ast.Call) and \
                    ci.dotted(st.value.func).split(".")[-1] in ("register_blueprint", "run"):
                continue
            if isinstance(st, ast.If) and "__name__" in self.src.seg(st.test):
                self.changes.add(str(mod.rel), "removed", "the Flask development server start-up block")
                continue
            if P.is_docstring(st):
                continue
            start = P.leading_comments_start(self.src, st)
            text = self.src.text[start:P.stmt_end(self.src, st)]
            defines = P.defined_names(st)
            if defines & self.money_consts and isinstance(st, ast.Assign) and isinstance(st.value, ast.Constant):
                lit = self.src.seg(st.value)
                a, b = self.src.span(st.value)
                text = P.apply_edits(text, [(a, b, f'Decimal("{lit}")')], start)
                self.changes.add(", ".join(defines), "exact money", f"{lit} is now Decimal(\"{lit}\")")
                services.append({"text": text, "uses": {"Decimal"}, "defines": defines, "line": st.lineno})
                continue
            services.append({"text": text, "uses": P.names_in(text), "defines": defines, "line": st.lineno})


