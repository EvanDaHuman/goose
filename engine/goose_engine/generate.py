def write_tests(out, scope, assessment):
    lines = ['"""Unit tests for the business rules, generated from the agreed rules in the scope."""',
             "from decimal import Decimal, ROUND_HALF_UP", "", "from app import services", "", ""]
    count = 0
    for r in scope["rules"]:
        fn = r["function"]
        tiers = sorted(r["tiers"], key=lambda t: float(t["min"]))
        cases = []
        low = Decimal(tiers[0]["min"]) - Decimal("0.01")
        cases.append(("below the first threshold", low, Decimal("0")))
        for t in tiers:
            m = Decimal(t["min"])
            rate = Decimal(t["rate"])
            if t["inclusive"]:
                cases.append((f"exactly at {m}", m, rate))
            half = None
            cents = int((m * 100).to_integral_value())
            for c in range(cents, cents + 5000):
                v = Decimal(c) / 100
                if (v * rate * 100) % 1 == Decimal("0.5"):
                    half = v
                    break
            if half is not None:
                cases.append((f"half cent above {m} rounds up", half, rate))
        for label, sub, rate in cases:
            disc = (sub * rate).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
            total = (sub - disc).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)
            count += 1
            name = re.sub(r"[^a-z0-9]+", "_", label.lower()).strip("_")
            lines += [f"def test_{fn}_{name}():",
                      f'    subtotal, discount, total = services.{fn}([(Decimal("{sub}"), 1)])',
                      f'    assert subtotal == Decimal("{sub}")',
                      f'    assert discount == Decimal("{disc}")',
                      f'    assert total == Decimal("{total}")', "", ""]
    if count == 0:
        lines += ["def test_services_import():", "    assert services is not None", ""]
    (out / "tests" / "test_business_rules.py").write_text("\n".join(lines).rstrip() + "\n")
    (out / "tests" / "__init__.py").write_text("")
    (out / "tests" / "conftest.py").write_text(
        'import os\nos.environ.setdefault("DATABASE_URL", "postgresql://unused/for-unit-tests")\n')


