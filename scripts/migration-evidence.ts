import fs from "node:fs";
import path from "node:path";
import { pool, q, one } from "../lib/db";
import { jobById } from "../lib/jobs";
import { J, readJson, sha256 } from "../lib/stages";
import { jobSpend } from "../lib/records";

const id = process.argv[2], output = process.argv[3];
try {
  if (!/^GS-\d+$/.test(id ?? "") || !output) throw new Error("Usage: npm run migration:evidence -- GS-id /path/evidence.json");
  const job = await jobById(id);
  if (!job || job.recipe !== "agent-replatform") throw new Error("No target-driven migration with this id");
  const plan = await one<any>("SELECT version,author_kind,naive_session_id,plan FROM plans WHERE job_id=$1 ORDER BY version DESC LIMIT 1", [id]);
  const attempts = await q("SELECT attempt,total,passed,failed,skipped,integrity_ok,verdict,created_at FROM check_runs WHERE job_id=$1 ORDER BY attempt", [id]);
  const sessions = await q("SELECT session_id,role,purpose,model,status,stop_reason,consumed_micro_usd,created_at FROM naive_sessions WHERE job_id=$1 ORDER BY id", [id]);
  const stages = await q("SELECT stage,attempt,status,runs,actor,started_at,finished_at,error FROM stage_runs WHERE job_id=$1 ORDER BY id", [id]);
  const approvals = await q("SELECT kind,decision,by_name,statement,at FROM approvals WHERE job_id=$1 ORDER BY id", [id]);
  const interventions = await q("SELECT kind,reason,minutes,at FROM interventions WHERE job_id=$1 ORDER BY id", [id]);
  const packageFile = J(job, "delivery", `${id}-delivery.zip`);
  const reportPath = J(job, "verify", `attempt-${job.attempt}`, "report.json");
  const report = fs.existsSync(reportPath) ? readJson(reportPath) : null;
  const c = plan?.plan?.migration_contract;
  const evidence = { generated_at: new Date().toISOString(), job: { id, title: job.title, kind: job.kind, mode: job.mode, stage: job.stage, status: job.status, goal: job.goal },
    target: c?.target, contract: c ? { id: c.id, legacy_requests: c.legacy_requests.length, new_requests: c.new_requests.length, persistence_requests: c.persistence_requests.length,
      data_assertions: c.data_assertions.length, data_changes: c.data_changes, manifest_sha256: job.checks_manifest_sha } : null,
    attempts, sessions, stages, approvals, interventions, spend_micro_usd: await jobSpend(id),
    delivery: fs.existsSync(packageFile) ? { sha256: sha256(packageFile), bytes: fs.statSync(packageFile).size } : null,
    limits: report?.not_tested ?? [],
    claims: { synthetic_customer: job.kind === "demo", paid_customer: false, production_deployment: false,
      agent_work: "Assessment and implementation sessions listed above; verifier/coordinator sessions are listed when invoked.",
      deterministic_work: "Inspection, snapshotting, contract guards, data transformations, compilation, independent verification, packaging and durable orchestration.",
      approvals: job.kind === "demo" ? "Fixture approvals are generated by the demonstration harness and are not real customer acceptance." : "See approval records." } };
  fs.mkdirSync(path.dirname(path.resolve(output)), { recursive: true });
  fs.writeFileSync(output, JSON.stringify(evidence, null, 2) + "\n");
  console.log(`Evidence exported for ${id}: ${output}`);
} finally { await pool.end(); }
